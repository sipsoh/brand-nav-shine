"use client";

import { useEffect, useState } from "react";
import {
  getDatasetInsights,
  type ComputedInsight,
  type SourceTrace,
} from "@/lib/api-client";

const SEVERITY_STYLES: Record<string, string> = {
  positive: "border-green-200 bg-green-50",
  negative: "border-red-200 bg-red-50",
  warning: "border-amber-200 bg-amber-50",
  opportunity: "border-indigo-200 bg-indigo-50",
  neutral: "border-neutral-200 bg-white",
};

export function InsightList({
  datasetId,
  getToken,
}: {
  datasetId: string;
  getToken: () => Promise<string | null>;
}) {
  const [insights, setInsights] = useState<ComputedInsight[] | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let cancelled = false;
    (async () => {
      try {
        const token = await getToken();
        if (!token) return;
        const result = await getDatasetInsights(token, datasetId);
        if (!cancelled) {
          setInsights(result.tables.flatMap((table) => table.insights));
        }
      } catch {
        if (!cancelled) setError("Could not compute insights for this dataset.");
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [datasetId, getToken]);

  if (error) return <p className="text-sm text-red-600">{error}</p>;
  if (insights === null) {
    return <p className="text-sm text-neutral-500">Computing insights…</p>;
  }
  if (insights.length === 0) {
    return (
      <p className="text-sm text-neutral-500">
        No notable patterns detected in this dataset yet.
      </p>
    );
  }

  return (
    <ul className="space-y-2">
      {insights.map((insight) => (
        <li
          key={insight.id}
          className={`rounded-lg border px-4 py-3 ${
            SEVERITY_STYLES[insight.severity] ?? SEVERITY_STYLES.neutral
          }`}
        >
          <p className="text-sm font-semibold text-neutral-900">{insight.headline}</p>
          <p className="mt-1 text-sm text-neutral-600">{insight.detail}</p>
          <SourceTraceDetails trace={insight.sourceTrace} />
        </li>
      ))}
    </ul>
  );
}

function SourceTraceDetails({ trace }: { trace: SourceTrace }) {
  return (
    <details className="mt-2">
      <summary className="cursor-pointer text-xs font-medium text-neutral-500 hover:text-neutral-700">
        How this was calculated
      </summary>
      <dl className="mt-2 space-y-1 rounded-md bg-white/70 p-3 text-xs text-neutral-600">
        <div>
          <dt className="inline font-medium">Calculation: </dt>
          <dd className="inline">{trace.calculation}</dd>
        </div>
        <div>
          <dt className="inline font-medium">Columns: </dt>
          <dd className="inline">{trace.columns.join(", ")}</dd>
        </div>
        {trace.filters.length > 0 && (
          <div>
            <dt className="inline font-medium">Filters: </dt>
            <dd className="inline">{trace.filters.join("; ")}</dd>
          </div>
        )}
        <div>
          <dt className="inline font-medium">Rows included: </dt>
          <dd className="inline">{trace.rowCount.toLocaleString()}</dd>
        </div>
        <div>
          <dt className="inline font-medium">Generated by: </dt>
          <dd className="inline">
            {trace.generatedBy === "code" ? "deterministic code" : trace.generatedBy}
          </dd>
        </div>
      </dl>
    </details>
  );
}
